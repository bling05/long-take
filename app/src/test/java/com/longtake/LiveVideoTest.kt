package com.longtake

import com.longtake.ai.FreeCheck
import com.longtake.youtube.TranscriptFetcher
import kotlinx.coroutines.runBlocking
import okhttp3.OkHttpClient
import okhttp3.Request
import org.json.JSONObject
import org.junit.Assume.assumeTrue
import org.junit.Test

/**
 * Runs the app's real transcript fetcher + free AI check against live YouTube videos.
 * Only runs when LIVE_VIDEOS is set, e.g. LIVE_VIDEOS="qNxRWO1Hmek,PLX4DApdGFnsm4gL8zREOZ7_it3-9_6IXM"
 * (a playlist ID means "the first few videos in that playlist").
 */
class LiveVideoTest {
    private val http = OkHttpClient()

    private fun get(url: String) = http.newCall(Request.Builder().url(url).header("User-Agent", "Mozilla/5.0").header("Cookie", "CONSENT=YES+1").build())
        .execute().use { it.body?.string().orEmpty() }

    private fun expand(id: String, perPlaylist: Int): List<String> =
        if (id.startsWith("@")) Regex("\"videoId\":\"([A-Za-z0-9_-]{11})\"").findAll(get("https://www.youtube.com/$id/videos"))
            .map { it.groupValues[1] }.distinct().take(perPlaylist).toList()
        else if (id.startsWith("PL")) Regex("\"videoId\":\"([A-Za-z0-9_-]{11})\"").findAll(get("https://www.youtube.com/playlist?list=$id"))
            .map { it.groupValues[1] }.distinct().take(perPlaylist).toList()
        else listOf(id)

    /** LIVE_PLAYLISTS="PLxxx,PLyyy": prints each playlist's title, size and how many different channels it draws from. */
    @Test fun livePlaylists() {
        val arg = System.getenv("LIVE_PLAYLISTS")
        assumeTrue("set LIVE_PLAYLISTS to run", !arg.isNullOrBlank())
        for (id in arg!!.split(",").map { it.trim() }) {
            val html = get("https://www.youtube.com/playlist?list=$id")
            val title = Regex("<title>(.*?)</title>").find(html)?.groupValues?.get(1)?.removeSuffix(" - YouTube")
            val vids = Regex("\"videoId\":\"([A-Za-z0-9_-]{11})\"").findAll(html).map { it.groupValues[1] }.distinct().count()
            val ids = Regex("\"videoId\":\"([A-Za-z0-9_-]{11})\"").findAll(html).map { it.groupValues[1] }.distinct().toList()
            val channels = ids.shuffled(java.util.Random(1)).take(20).mapNotNull { v ->
                runCatching { JSONObject(get("https://www.youtube.com/oembed?format=json&url=https://www.youtube.com/watch?v=$v")).optString("author_name") }.getOrNull()
            }
            val total = Regex("\"numVideosText\":\\{\"runs\":\\[\\{\"text\":\"([0-9,]+)\"").find(html)?.groupValues?.get(1)
                ?: Regex("([0-9,]+) videos").find(html)?.groupValues?.get(1)
            val top = channels.groupingBy { it }.eachCount().entries.sortedByDescending { it.value }.take(6).joinToString { "${it.key}(${it.value})" }
            println("=== $id | $title | total=$total | firstPage=$vids | distinctChannels=${channels.distinct().size} | top: $top")
        }
    }

    @Test fun liveVideos() = runBlocking {
        val arg = System.getenv("LIVE_VIDEOS")
        assumeTrue("set LIVE_VIDEOS to run", !arg.isNullOrBlank())
        val fetcher = TranscriptFetcher(http)
        for ((id, curated) in arg!!.split(",").flatMap { a -> expand(a.trim(), 3).map { it to a.trim().startsWith("PL") } }) {
            val meta = runCatching { JSONObject(get("https://www.youtube.com/oembed?format=json&url=https://www.youtube.com/watch?v=$id")) }.getOrNull()
            println("=== $id | ${meta?.optString("title")} | ${meta?.optString("author_name")}")
            val t = runCatching { fetcher.fetch(id) }.onFailure { println("  fetch error: $it") }.getOrNull()
            if (t == null) { println("  NO TRANSCRIPT"); continue }
            println("  transcript: ${t.wordCount} words, auto=${t.isAutoGenerated}, lang=${t.language}")
            val r = FreeCheck.run(t.text, null)
            println("  FREE CHECK: score=${r.score} verdict=${r.verdict} ${FreeCheck.details}")
            r.reasons.forEach { println("    - $it") }
            val sp = com.longtake.ai.EssayScore.speech(t.text, t.durationSec)
            val e = com.longtake.ai.EssayScore.score(t.title, t.description, t.durationSec, curated, false, sp)
            println("  ESSAY: score=${e.score} format=${e.format.label} filler/1k=${"%.1f".format(sp.fillerPer1k)} wpm=${sp.wordsPerMinute} min=${t.durationSec / 60}")
            e.reasons.forEach { println("    * $it") }
            java.io.File(System.getProperty("java.io.tmpdir"), "transcript_$id.txt").writeText(t.text)
        }
    }

    /** CLAUDE_TEST_KEY=... LIVE_VIDEOS=id,id : writes synopses the way the app does and prints them. */
    @Test fun liveSynopsis() = runBlocking {
        val key = System.getenv("CLAUDE_TEST_KEY"); val ids = System.getenv("LIVE_VIDEOS")
        assumeTrue("set CLAUDE_TEST_KEY and LIVE_VIDEOS", !key.isNullOrBlank() && !ids.isNullOrBlank())
        for (id in ids!!.split(",").map { it.trim() }) {
            val t = runCatching { TranscriptFetcher(http).fetch(id) }.getOrNull()
            val meta = runCatching { JSONObject(get("https://www.youtube.com/oembed?format=json&url=https://www.youtube.com/watch?v=$id")) }.getOrNull()
            val title = t?.title?.ifBlank { null } ?: meta?.optString("title").orEmpty()
            val r = com.longtake.ai.SynopsisWriter().write(key!!, title, meta?.optString("author_name").orEmpty(), t?.description.orEmpty(), t?.text)
            println("SYNOPSIS $id | $title\n  ${r.synopsis}\n  topics=${r.topics} mood=${r.mood} transcript=${t != null} tokens in=${r.inputTokens} out=${r.outputTokens}")
        }
    }

    /** CLAUDE_TEST_KEY=... LIVE_VIDEOS=id : runs the app's Claude check on a real transcript. */
    @Test fun liveClaude() = runBlocking {
        val key = System.getenv("CLAUDE_TEST_KEY"); val ids = System.getenv("LIVE_VIDEOS")
        assumeTrue("set CLAUDE_TEST_KEY", !key.isNullOrBlank() && !ids.isNullOrBlank())
        for (id in ids!!.split(",")) {
            val t = TranscriptFetcher(http).fetch(id.trim()) ?: run { println("no transcript $id"); return@runBlocking }
            val start = System.currentTimeMillis()
            try {
                val r = com.longtake.ai.ClaudeCheck().check(key!!, com.longtake.data.ClaudeModel.HAIKU, t.title, "", t.text)
                println("CLAUDE $id: ${r.verdict} ${r.confidence}% in ${System.currentTimeMillis() - start} ms tokens in=${r.inputTokens} out=${r.outputTokens}")
            } catch (e: Throwable) { println("CLAUDE $id FAILED after ${System.currentTimeMillis() - start} ms: $e"); e.printStackTrace() }
        }
    }
}
