package com.longtake.youtube

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.io.IOException

/**
 * Fetches a video's captions the same way the YouTube apps do (YouTube's official API only
 * gives captions to the video's owner). This is unofficial and may break if YouTube changes things.
 */
/** YouTube only shows this video to signed-in adults, so its captions can't be read. */
class AgeRestrictedException : Exception("Age-restricted video")

class TranscriptFetcher(private val http: OkHttpClient) {

    data class Transcript(
        val text: String,
        val isAutoGenerated: Boolean,
        val language: String,
        val durationSec: Long = 0,
        val title: String = "",
        val description: String = "",
    ) {
        val wordCount get() = text.split(Regex("\\s+")).count { it.isNotBlank() }
    }

    private val ua = "com.google.android.youtube/20.10.38 (Linux; U; Android 14) gzip"

    /**
     * Returns null only when YouTube says the video really has no captions.
     * Throws [IOException] when the download fails (no internet, YouTube refusing requests…),
     * so the caller can try again later instead of recording "no transcript".
     */
    suspend fun fetch(videoId: String): Transcript? = withContext(Dispatchers.IO) {
        val player = player(videoId)
        val tracks = player.tracks
        if (tracks.isEmpty()) return@withContext null
        // Prefer creator-made English, then auto English, then anything.
        val pick = tracks.firstOrNull { it.lang.startsWith("en") && !it.auto }
            ?: tracks.firstOrNull { it.lang.startsWith("en") }
            ?: tracks.first()
        val url = pick.baseUrl.replace(Regex("&fmt=[^&]*"), "")
        val xml = http.newCall(
            Request.Builder().url(url).header("User-Agent", ua).header("Cookie", "CONSENT=YES+1").build()
        ).execute().use { if (it.isSuccessful) it.body?.string() else null }
            ?: throw IOException("Caption download failed")
        val text = parseXml(xml)
        if (text.isBlank()) null else Transcript(text, pick.auto, pick.lang, player.durationSec, player.title, player.description)
    }

    private data class Track(val baseUrl: String, val lang: String, val auto: Boolean)

    private data class Player(val tracks: List<Track>, val durationSec: Long, val title: String, val description: String)

    private fun player(videoId: String): Player {
        val body = JSONObject()
            .put("context", JSONObject().put("client", JSONObject()
                .put("clientName", "ANDROID")
                .put("clientVersion", "20.10.38")
                .put("androidSdkVersion", 34)
                .put("hl", "en")))
            .put("videoId", videoId)
            // Click through YouTube's "this video may contain sensitive topics" warning, as the app would.
            .put("contentCheckOk", true)
            .put("racyCheckOk", true)
            .toString()
            .toRequestBody("application/json".toMediaType())
        val req = Request.Builder()
            .url("https://www.youtube.com/youtubei/v1/player?prettyPrint=false")
            .header("User-Agent", ua)
            .header("Cookie", "CONSENT=YES+1")
            .post(body)
            .build()
        val json = http.newCall(req).execute().use { if (it.isSuccessful) it.body?.string() else null }
            ?: throw IOException("YouTube didn't answer")
        val root = runCatching { JSONObject(json) }.getOrNull() ?: throw IOException("YouTube sent something unreadable")
        // Anything but OK (e.g. "confirm you're not a bot") means YouTube held back the details,
        // not that the video lacks captions.
        val playability = root.optJSONObject("playabilityStatus")
        val status = playability?.optString("status").orEmpty()
        val reason = playability?.optString("reason").orEmpty()
        if (status != "OK") {
            // Age-restricted videos always need a signed-in account, so retrying won't help.
            val ageGated = status == "LOGIN_REQUIRED" && (reason.contains("inappropriate", true) || reason.contains("confirm your age", true))
            if (ageGated) throw AgeRestrictedException()
            throw IOException("YouTube refused the request ($status: $reason)")
        }
        val details = root.optJSONObject("videoDetails")
        val arr = runCatching {
            root.getJSONObject("captions")
                .getJSONObject("playerCaptionsTracklistRenderer")
                .getJSONArray("captionTracks")
        }.getOrNull()
        val tracks = if (arr == null) emptyList() else (0 until arr.length()).mapNotNull { i ->
            val t = arr.optJSONObject(i) ?: return@mapNotNull null
            val url = t.optString("baseUrl").takeIf { it.isNotBlank() } ?: return@mapNotNull null
            Track(url, t.optString("languageCode"), t.optString("kind") == "asr")
        }
        return Player(
            tracks,
            details?.optString("lengthSeconds")?.toLongOrNull() ?: 0,
            details?.optString("title").orEmpty(),
            details?.optString("shortDescription").orEmpty(),
        )
    }

    companion object {
        fun parseXml(xml: String): String {
            // Handles both the classic <text> format and the newer srv3 <p> format.
            val pieces = Regex("<(?:text|p)\\b[^>]*>(.*?)</(?:text|p)>", RegexOption.DOT_MATCHES_ALL)
                .findAll(xml)
                .map { it.groupValues[1].replace(Regex("<[^>]+>"), "") }
                .map { unescape(unescape(it)) } // captions are often double-escaped (&amp;#39;)
                .map { it.replace('\n', ' ').trim() }
                .filter { it.isNotBlank() && !it.startsWith("[") }
            return pieces.joinToString(" ")
        }

        private fun unescape(s: String): String =
            Regex("&(#x?[0-9a-fA-F]+|amp|lt|gt|quot|apos|nbsp);").replace(s) { m ->
                when (val e = m.groupValues[1]) {
                    "amp" -> "&"; "lt" -> "<"; "gt" -> ">"; "quot" -> "\""; "apos" -> "'"; "nbsp" -> " "
                    else -> {
                        val code = if (e.startsWith("#x")) e.drop(2).toIntOrNull(16) else e.drop(1).toIntOrNull()
                        code?.let { String(Character.toChars(it)) } ?: m.value
                    }
                }
            }
    }
}
